import type { EventEnquiry, EnquiryService } from '~~/prisma/generated/client'
import { buildWhatsAppLink, buildEnquiryMessage, formatPhoneForDisplay } from '#shared/utils/whatsapp'
import { formatDate, firstName } from '#shared/utils/format'

type EnquiryWithServices = EventEnquiry & { services: EnquiryService[] }

function enquiryRows(enquiry: EnquiryWithServices): Array<[string, string | null | undefined]> {
  return [
    ['Reference', enquiry.reference],
    ['Event type', enquiry.eventTypeOther ? `${enquiry.eventTypeLabel} — ${enquiry.eventTypeOther}` : enquiry.eventTypeLabel],
    ['Event date', enquiry.eventDate ? formatDate(enquiry.eventDate) : (enquiry.dateIsFlexible ? 'Not yet confirmed' : '')],
    ['Location', enquiry.location],
    ['Venue', enquiry.venue || (enquiry.venueNotConfirmed ? 'Not yet confirmed' : '')],
    ['Guests', enquiry.guestCount ? String(enquiry.guestCount) : ''],
    ['Services', enquiry.services.map(s => s.label).join(', ')],
    ['Budget range', enquiry.budgetLabel],
    ['Theme', enquiry.theme],
    ['Colours', enquiry.colours],
    ['Vision', enquiry.vision],
    ['Additional requests', enquiry.additionalRequests],
  ]
}

export async function notifyAdminOfEnquiry(enquiry: EnquiryWithServices, imageCount: number): Promise<boolean> {
  const to = await getAdminNotificationEmail()
  const siteUrl = useRuntimeConfig().public.siteUrl
  const rows: Array<[string, string | null | undefined]> = [
    ...enquiryRows(enquiry),
    ['Name', enquiry.fullName],
    ['Phone', enquiry.phone],
    ['Email', enquiry.email],
    ['Preferred contact', enquiry.preferredContact],
    ['Inspiration images', imageCount ? `${imageCount} attached (view in dashboard)` : ''],
  ]
  const adminUrl = `${siteUrl}/admin/enquiries/${enquiry.id}`
  const html = renderEmailLayout(
    `New enquiry: ${enquiry.eventTypeLabel}`,
    `${renderDetailRows(rows)}
     <p style="margin:24px 0 0;"><a href="${adminUrl}" style="display:inline-block;background:#3b0019;color:#ece7c5;text-decoration:none;padding:12px 22px;font-size:12px;letter-spacing:0.2em;text-transform:uppercase;">Open in dashboard</a></p>`,
    'This notification was generated by the Prissy Plans Events website.',
  )
  const text = rows.filter(([, v]) => v).map(([k, v]) => `${k}: ${v}`).join('\n') + `\n\nOpen: ${adminUrl}`
  if (!to) {
    console.info(`[mail] Admin notification inbox is not configured. Enquiry ${enquiry.reference} saved.\n${text}`)
    return false
  }
  const result = await sendMail({ to, subject: `New event enquiry ${enquiry.reference} — ${enquiry.eventTypeLabel}`, html, text, replyTo: enquiry.email })
  return result.delivered
}

export async function sendClientConfirmation(enquiry: EnquiryWithServices): Promise<boolean> {
  const settings = await getSettings()
  const whatsapp = await getWhatsAppNumber(settings)
  const waLink = whatsapp ? buildWhatsAppLink(whatsapp, buildEnquiryMessage({ reference: enquiry.reference, name: enquiry.fullName })) : ''
  const successMessage = settings['enquiry.successMessage']
  const rows = enquiryRows(enquiry)

  const html = renderEmailLayout(
    `Thank you, ${escapeHtml(firstName(enquiry.fullName))}`,
    `<p style="font-size:15px;line-height:1.7;margin:0 0 20px;">${escapeHtml(successMessage)}</p>
     <p style="font-size:15px;line-height:1.7;margin:0 0 20px;">Your enquiry reference is <strong>${escapeHtml(enquiry.reference)}</strong>. Here is a summary of what you shared with us:</p>
     ${renderDetailRows(rows)}
     ${waLink ? `<p style="margin:24px 0 0;"><a href="${waLink}" style="display:inline-block;background:#25d366;color:#ffffff;text-decoration:none;padding:12px 22px;font-size:12px;letter-spacing:0.2em;text-transform:uppercase;">Chat with us on WhatsApp</a></p>` : ''}`,
    `Prissy Plans Events · ${escapeHtml(settings['contact.location'] || 'Kenya')}${whatsapp ? ` · WhatsApp ${escapeHtml(formatPhoneForDisplay(whatsapp))}` : ''}`,
  )
  const text = `${successMessage}\n\nReference: ${enquiry.reference}\n\n${rows.filter(([, v]) => v).map(([k, v]) => `${k}: ${v}`).join('\n')}${waLink ? `\n\nWhatsApp: ${waLink}` : ''}`
  const result = await sendMail({ to: enquiry.email, subject: `We received your enquiry (${enquiry.reference}) — Prissy Plans Events`, html, text })
  return result.delivered
}

export async function notifyAdminOfContactMessage(enquiry: EnquiryWithServices): Promise<boolean> {
  const to = await getAdminNotificationEmail()
  const siteUrl = useRuntimeConfig().public.siteUrl
  const rows: Array<[string, string | null | undefined]> = [
    ['Reference', enquiry.reference],
    ['Name', enquiry.fullName],
    ['Email', enquiry.email],
    ['Phone', enquiry.phone],
    ['Event type', enquiry.eventTypeOther],
    ['Message', enquiry.vision],
  ]
  const text = rows.filter(([, v]) => v).map(([k, v]) => `${k}: ${v}`).join('\n')
  if (!to) {
    console.info(`[mail] Admin inbox not configured. Contact message ${enquiry.reference} saved.\n${text}`)
    return false
  }
  const html = renderEmailLayout('New contact message', `${renderDetailRows(rows)}<p style="margin:24px 0 0;"><a href="${siteUrl}/admin/enquiries/${enquiry.id}">Open in dashboard</a></p>`)
  const result = await sendMail({ to, subject: `New contact message ${enquiry.reference}`, html, text, replyTo: enquiry.email })
  return result.delivered
}
